#!/usr/bin/env python3
"""Generate components/apple2Core/apple2Fast6502.inc from the decoder in chips/m6502.h.

The cycle-stepped decoder (one `case (opcode<<3)|cycle` per bus cycle) is unrolled into one
straight-line block per opcode. The micro-operation bodies are copied verbatim, so the sequence of
bus accesses (address, direction, data), the register effects and the cycle counts are identical to
m6502_tick(); only the per-cycle dispatch and the 64-bit pin word are gone.

Usage: python3 tools/genM6502Fast.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parents[1]
header = root / "components/apple2Core/third_party/chips/m6502.h"
output = root / "components/apple2Core/apple2Fast6502.inc"

caseRe = re.compile(r"^\s*case \((0x[0-9A-F]{2})<<3\)\|(\d): (.*)break;\s*$")
ops = {}
for line in header.read_text().splitlines():
    m = caseRe.match(line)
    if m:
        ops.setdefault(int(m.group(1), 16), {})[int(m.group(2))] = m.group(3).strip()

assert len(ops) == 256, len(ops)

out = []
out.append("// GENERATED by tools/genM6502Fast.py from chips/m6502.h - do not edit by hand.")
out.append("// Included by apple2Core.c inside fastRun6502(); relies on the macros defined there.")
out.append("switch (fastData) {")
for op in range(256):
    cycles = ops[op]
    bodies = [cycles[k] for k in range(8)]
    if any("c->IR--" in b for b in bodies):
        # JAM opcodes repeat one cycle forever: leave them to the cycle-stepped core.
        out.append("case 0x%02X: goto fastBail;" % op)
        continue
    last = max(k for k in range(8) if bodies[k] != "assert(false);")
    skipTargets = set()
    for k in range(last + 1):
        if "c->IR+=" in bodies[k]:
            skipTargets.add(k + 2)
    out.append("case 0x%02X: {" % op)
    for k in range(last + 1):
        body = bodies[k]
        if k in skipTargets:
            out.append("fastL%02X_%d:;" % (op, k))
        hasSkip = "c->IR+=" in body
        body = re.sub(r"c->IR\+=([^;]*);", r"fastSkip=(\1);", body)
        out.append("  FAST_CYCLE_BEGIN();")
        out.append("  " + body)
        out.append("  FAST_BUS();")
        if hasSkip:
            out.append("  if (fastSkip) { fastSkip = 0; goto fastL%02X_%d; }" % (op, k + 2))
        if k == last:
            out.append("  FAST_DONE();")
        else:
            out.append("  if (fastSync) { FAST_DONE(); }")
    out.append("}")
out.append("default: goto fastBail;")
out.append("}")
output.write_text("\n".join(out) + "\n")
print("wrote", output, len(out), "lines")
