#!/usr/bin/env python3
"""Instruction-table model, NOT measured hardware results or a bus simulation."""
import json
from pathlib import Path


def model(scale=1):
  blocks = 32 * scale
  integer = blocks * (12 + 32768 * 13 + 32767 * 17 + 5 + 16 + 2 + 16) - 12
  flags = [True] * 8192
  sieve = 12 + 9 + 8192 * 10 + 4
  marks = 0
  for prime in range(2, 91):
    sieve += 19
    if not flags[prime]:
      sieve += 16
    else:
      sieve += 4 + 2 + 133 + 2
      positions = list(range(prime * prime, 8192, prime))
      marks += len(positions)
      for multiple in positions:
        flags[multiple] = False
      sieve += len(positions) * (19 + 3 + 4 + 16) - 12
    sieve += 2 + 4 + (16 if prime < 90 else 4)
  sieve += 3 + 4
  for candidate in range(2, 8192):
    sieve += 19 + (4 + 2 if flags[candidate] else 16)
    sieve += 2 + 4 + (16 if candidate < 8191 else 4)
  sieve += 4 + 4 + 2 + 16
  sieve = sieve * 20 * scale - 12
  return {'INTEGER': integer, 'SIEVE': sieve}, marks


def main():
  cycles, marks = model()
  report = {'kind': 'instruction-table estimate; NOT measured hardware',
            'scale': 1, 'cycles': cycles, 'compositeStoresPerSieve': marks,
            'milliseconds': {str(mhz): {name: round(count / (mhz * 1000))
                                      for name, count in cycles.items()}
                             for mhz in (5, 8, 10)},
            'assumptions': '8086; no memory wait states, interrupts, bus contention or prefetch stalls; '
                           'MUL r16 charged 133 clocks; timer/prologue/output excluded.'}
  print(json.dumps(report, indent=2))
  folder = Path(__file__).resolve().parent
  lines = ['; Generated by reference_model.py: instruction-table estimates, not measurements.']
  for name in cycles:
    lines.append(f'{name.lower()}ModelMs equ {report["milliseconds"]["5"][name]}')
  (folder / 'reference.inc').write_text('\n'.join(lines) + '\n')

if __name__ == '__main__':
  main()
