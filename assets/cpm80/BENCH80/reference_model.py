#!/usr/bin/env python3
"""Z80 T-state model of BENCH80, NOT measured hardware results or a bus simulation."""
import json
from pathlib import Path

integerBlocksPerScale = 4
sieveRoundsPerScale = 10


def integerCycles(scale=1):
  total = 0
  for blocks in range(integerBlocksPerScale * scale):
    ax, bx = 0x1234, 0x5678
    cycles = 30
    for _ in range(32768):
      ax = (ax + bx) & 0xFFFF
      ax ^= 0xA55A
      carry = ax >> 15
      ax = (ax << 1) & 0xFFFF
      cycles += 91
      if carry:
        ax |= 1
        cycles += 12 + 4
      else:
        cycles += 7
      low = (bx & 0xFF) + 17
      bx = (bx + 17) & 0xFFFF
      cycles += 12 if low < 256 else 7 + 4
    assert (ax, bx) == (0x4ED8, 0xD678)
    total += cycles + 72
  return total


def sieveCycles(scale=1):
  flags = [True] * 8192
  cycles = 30 + 21 * 8191 - 5 + 20
  prime = 2
  square = 4
  while prime < 91:
    cycles += 32
    if not flags[prime]:
      cycles += 12
    else:
      cycles += 7 + 21
      position = square
      while position < 8192:
        flags[position] = False
        position += prime
        cycles += 44 if position < 8192 else 39
    cycles += 61 + (12 if prime < 90 else 7)
    square += 2 * prime + 1
    prime += 1
  cycles += 30
  primes = 0
  for candidate in range(2, 8192):
    if flags[candidate]:
      primes += 1
      cycles += 54
    else:
      cycles += 53
  assert primes == 1028
  cycles += 36
  return cycles * sieveRoundsPerScale * scale


def main():
  cycles = {'INTEGER': integerCycles(), 'SIEVE': sieveCycles()}
  report = {'kind': 'instruction-table estimate; NOT measured hardware', 'scale': 1,
            'tStates': cycles,
            'milliseconds': {str(mhz): {name: round(count / (mhz * 1000))
                                      for name, count in cycles.items()}
                             for mhz in (1, 2, 4)},
            'assumptions': 'Z80; no wait states or interrupts; timer, dots and output excluded.'}
  print(json.dumps(report, indent=2))
  lines = ['; Generated by reference_model.py: instruction-table estimates, not measurements.']
  for name in cycles:
    lines.append(f'{name.lower()}ModelMs: equ {report["milliseconds"]["1"][name]}')
  (Path(__file__).resolve().parent / 'reference.inc').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
  main()
